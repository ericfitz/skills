#!/usr/bin/env python3
"""Generate Codex-native plugin manifests from the Claude Code ones.

Source of truth: .claude-plugin/marketplace.json plus each plugin's
.claude-plugin/plugin.json. Emits .agents/plugins/marketplace.json and one
<plugin>/.codex-plugin/plugin.json per plugin so the repo also works as a
plugin marketplace in OpenAI Codex. A skill whose SKILL.md frontmatter sets
`disable-model-invocation: true` also gets skills/<skill>/agents/openai.yaml
with `policy.allow_implicit_invocation: false`, Codex's per-skill equivalent.
--check verifies the committed files match a fresh regeneration, and that no
generated openai.yaml is left over, without writing anything.
"""

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

SKILL_POLICY_HEADER = (
    "# Generated by scripts/gen_codex_manifests.py from SKILL.md disable-model-invocation; do not edit.\n"
)
SKILL_POLICY = SKILL_POLICY_HEADER + "policy:\n  allow_implicit_invocation: false\n"


class GenerationError(ValueError):
    """A structural problem in the Claude manifests that blocks generation."""


def _render(obj: dict) -> str:
    return json.dumps(obj, indent=2) + "\n"


def _load_json(path: Path, label: str) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise GenerationError(f"{label}: cannot read {path.name}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise GenerationError(f"{label}: invalid JSON: {exc}") from exc
    if not isinstance(data, dict):
        raise GenerationError(f"{label}: expected a JSON object")
    return data


def _disable_model_invocation(skill_md: Path, label: str) -> bool:
    """The SKILL.md frontmatter disable-model-invocation flag; absent is False, anything but true/false fails."""
    lines = skill_md.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return False
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, sep, value = line.partition(":")
        if sep and key.strip() == "disable-model-invocation":
            value = value.strip().strip("\"'")
            if value == "true":
                return True
            if value == "false":
                return False
            raise GenerationError(f"{label}: disable-model-invocation must be true or false, got {value!r}")
    return False


def _skill_policies(plugin_dir: Path, name: str) -> dict[Path, str]:
    """Map agents/openai.yaml to its content for each skill that disables model invocation."""
    out: dict[Path, str] = {}
    for skill_dir in sorted(p for p in (plugin_dir / "skills").iterdir() if p.is_dir()):
        skill_md = skill_dir / "SKILL.md"
        label = f"{name}/{skill_dir.name}"
        if not skill_md.is_file() or not _disable_model_invocation(skill_md, label):
            continue
        target = skill_dir / "agents" / "openai.yaml"
        if target.is_file() and not target.read_text(encoding="utf-8").startswith(SKILL_POLICY_HEADER):
            raise GenerationError(
                f"{label}: agents/openai.yaml is hand-written; add policy.allow_implicit_invocation: false "
                "to it by hand or remove it so it can be generated"
            )
        out[target] = SKILL_POLICY
    return out


def stale_policies(repo: Path, rendered: dict[Path, str]) -> list[Path]:
    """Generated skill openai.yaml files that a fresh generation no longer produces."""
    return sorted(
        path
        for path in repo.glob("*/skills/*/agents/openai.yaml")
        if path not in rendered and path.read_text(encoding="utf-8").startswith(SKILL_POLICY_HEADER)
    )


def generate(repo: Path) -> dict[Path, str]:
    """Map each Codex manifest path to its rendered JSON content."""
    marketplace = _load_json(repo / ".claude-plugin" / "marketplace.json", "marketplace.json")
    plugins = marketplace.get("plugins")
    if not isinstance(plugins, list):
        raise GenerationError('marketplace.json: missing "plugins" list')
    if not marketplace.get("name"):
        raise GenerationError('marketplace.json: missing "name"')
    seen: set[str] = set()
    entries: list[dict] = []
    out: dict[Path, str] = {}
    for entry in plugins:
        if not isinstance(entry, dict) or not entry.get("name"):
            raise GenerationError(f'marketplace.json: entry missing "name": {entry!r}')
        name = entry["name"]
        if name in seen:
            raise GenerationError(f"duplicate plugin name in marketplace.json: {name}")
        seen.add(name)
        source = entry.get("source")
        if not isinstance(source, str) or not source.startswith("./"):
            raise GenerationError(f"{name}: expected string source './<dir>', got {source!r}")
        plugin_dir = repo / source
        claude_manifest = plugin_dir / ".claude-plugin" / "plugin.json"
        if not claude_manifest.is_file():
            raise GenerationError(f"{name}: missing {source}/.claude-plugin/plugin.json")
        if not (plugin_dir / "skills").is_dir():
            raise GenerationError(f"{name}: missing {source}/skills/ directory")
        pdata = _load_json(claude_manifest, name)
        if pdata.get("name") != name:
            raise GenerationError(f"{name}: plugin.json name is {pdata.get('name')!r}, expected {name!r}")
        missing = [key for key in ("version", "description") if not pdata.get(key)]
        if missing:
            raise GenerationError(f"{name}: plugin.json missing {', '.join(missing)}")
        codex_manifest = {"name": name, "version": pdata["version"], "description": pdata["description"]}
        if "author" in pdata:
            codex_manifest["author"] = pdata["author"]
        codex_manifest["skills"] = "./skills/"
        out[plugin_dir / ".codex-plugin" / "plugin.json"] = _render(codex_manifest)
        out.update(_skill_policies(plugin_dir, name))
        codex_entry: dict = {"name": name}
        if "category" in entry:
            codex_entry["category"] = entry["category"]
        codex_entry["source"] = {"source": "local", "path": source}
        entries.append(codex_entry)
    out[repo / ".agents" / "plugins" / "marketplace.json"] = _render({"name": marketplace["name"], "plugins": entries})
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=REPO, help="repo root (default: this repo)")
    parser.add_argument("--check", action="store_true", help="verify committed files match; write nothing")
    args = parser.parse_args()
    try:
        rendered = generate(args.repo)
    except GenerationError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2
    if args.check:
        drift = [
            path
            for path, content in rendered.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        ]
        stale = stale_policies(args.repo, rendered)
        if drift or stale:
            for path in sorted(drift):
                print(f"DRIFT: {path.relative_to(args.repo)}", file=sys.stderr)
            for path in stale:
                print(f"STALE: {path.relative_to(args.repo)}", file=sys.stderr)
            print("Run: uv run scripts/gen_codex_manifests.py", file=sys.stderr)
            return 1
        print(f"OK: {len(rendered)} Codex manifests in sync")
        return 0
    for path, content in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(args.repo)}")
    for path in stale_policies(args.repo, rendered):
        path.unlink()
        if not any(path.parent.iterdir()):
            path.parent.rmdir()
        print(f"removed {path.relative_to(args.repo)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
